package ejercicio2;

public class TarjetaDeVisitaParameter {
	public int nIF;
	public String nombreEmpresa;
	public int numTelefono;
	public String email;

	public TarjetaDeVisitaParameter(int nIF, String nombreEmpresa, int numTelefono, String email) {
		this.nIF = nIF;
		this.nombreEmpresa = nombreEmpresa;
		this.numTelefono = numTelefono;
		this.email = email;
	}
}